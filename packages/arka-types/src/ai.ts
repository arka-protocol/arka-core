/**
 * Simulation result
 */
export interface SimulationResult {
  /** Unique identifier for the simulation */
  id: string;

  /** Input rules that were simulated */
  inputRules: ArkaRule[];

  /** Time window used */
  timeWindow: {
    start: string;
    end: string;
  };

  /** Number of events processed */
  eventsProcessed: number;

  /** Results with current rules */
  currentResults?: {
    allowed: number;
    denied: number;
    flagged: number;
  };

  /** Results with proposed rules */
  proposedResults: {
    allowed: number;
    denied: number;
    flagged: number;
  };

  /** Impact analysis */
  impact: {
    allowedDelta: number;
    deniedDelta: number;
    flaggedDelta: number;
    percentageChange: number;
  };

  /** AI-generated summary */
  summary: string;

  /** Detailed breakdown by rule */
  ruleBreakdown: Record<string, {
    matched: number;
    passed: number;
    failed: number;
  }>;

  /** ISO timestamp when simulation was run */
  createdAt: string;

  /** Related proposal ID if applicable */
  proposalId?: string;
}

