/**
 * Unique identifier for ARKA entities (string alias for type safety)
 */
export type ArkaEntityId = string;

/**
 * Risk score produced by the Predictive Risk Engine (PPRE)
 *
 * Represents a quantified risk assessment for any ARKA entity.
 * Used by the AI layer to score loans, accounts, customers, devices, etc.
 */
export interface RiskScore {
  /** Unique identifier for this risk score */
  id: string;

  /** ID of the entity being scored */
  entityId: ArkaEntityId;

  /** Type of entity (e.g., "Loan", "Customer", "Account") */
  entityType: string;

  /** Risk score from 0 (lowest risk) to 1 (highest risk) */
  score: number;

  /** Human-readable reasons explaining the score */
  reasons: string[];

  /** Optional labels for categorization (e.g., "high-risk", "fraud-suspect") */
  labels?: string[];

  /** Confidence level of the score (0-1) */
  confidence: number;

  /** Model or algorithm version that produced this score */
  modelVersion: string;

  /** ISO timestamp when the score was computed */
  createdAt: string;

  /** Additional metadata */
  metadata?: Record<string, unknown>;
}

/**
 * Severity levels for anomaly signals
 */
export type AnomalySeverity = 'LOW' | 'MEDIUM' | 'HIGH' | 'CRITICAL';

/**
 * Type of anomaly detected
 */
export type AnomalyType =
  | 'UNUSUAL_PATTERN'
  | 'THRESHOLD_BREACH'
  | 'VELOCITY_SPIKE'
  | 'BEHAVIORAL_DEVIATION'
  | 'STATISTICAL_OUTLIER'
  | 'RULE_CONFLICT'
  | 'DATA_QUALITY';

/**
 * Signal produced when an anomaly is detected in the event stream
 *
 * Used by the AI Monitor to flag unusual patterns, threshold breaches,
 * or behavioral deviations that warrant human attention.
 */
export interface AnomalySignal {
  /** Unique identifier for this signal */
  id: string;

  /** Type of anomaly detected */
  type: AnomalyType;

  /** Severity level */
  severity: AnomalySeverity;

  /** Human-readable description of the anomaly */
  description: string;

  /** IDs of events that triggered this signal */
  triggeringEventIds: string[];

  /** Entity ID if the anomaly is entity-specific */
  entityId?: ArkaEntityId;

  /** Entity type if the anomaly is entity-specific */
  entityType?: string;

  /** Anomaly score (0-1, higher = more anomalous) */
  anomalyScore: number;

  /** Baseline value for comparison (if applicable) */
  baseline?: number;

  /** Observed value that triggered the anomaly */
  observedValue?: number;

  /** Recommended actions */
  recommendations?: string[];

  /** ISO timestamp when the anomaly was detected */
  detectedAt: string;

  /** Additional context */
  context?: Record<string, unknown>;
}

/**
 * Risk impact levels for remediation suggestions
 */
export type RiskImpact = 'LOW' | 'MEDIUM' | 'HIGH';

/**
 * Suggestion produced by the AI Remediation Engine
 *
 * Represents a safe, policy-constrained action to fix an issue.
 * Always designed for human "Approve / Reject" workflows.
 */
export interface RemediationSuggestion {
  /** Unique identifier for this suggestion */
  id: string;

  /** Short title describing the action */
  title: string;

  /** Detailed description of what the action will do */
  description: string;

  /** Expected impact on risk level */
  riskImpact: RiskImpact;

  /** Whether human approval is required before execution */
  requiresApproval: boolean;

  /** Confidence in this suggestion (0-1) */
  confidence: number;

  /** Estimated effectiveness (0-1) */
  estimatedEffectiveness: number;

  /** Prerequisites that must be met */
  prerequisites?: string[];

  /** Potential side effects to consider */
  sideEffects?: string[];

  /** ISO timestamp when the suggestion was generated */
  createdAt: string;

  /** Additional metadata */
  metadata?: Record<string, unknown>;
}

/**
 * Summary of an incident for AI-Aware Mode
 *
 * Generated by the AI Monitor when multiple related anomalies
 * are detected and need to be reported as a cohesive incident.
 */
export interface IncidentSummary {
  /** Unique identifier for this incident */
  id: string;

  /** Short title for the incident */
  title: string;

  /** Detailed AI-generated narrative of what happened */
  narrative: string;

  /** Severity level of the incident */
  severity: AnomalySeverity;

  /** Anomaly signals that are part of this incident */
  relatedSignals: AnomalySignal[];

  /** Affected entity IDs */
  affectedEntities: ArkaEntityId[];

  /** Suggested remediation actions */
  suggestedActions: RemediationSuggestion[];

  /** Current status of the incident */
  status: 'OPEN' | 'INVESTIGATING' | 'RESOLVED' | 'DISMISSED';

  /** ISO timestamp when the incident was created */
  createdAt: string;

  /** ISO timestamp when the incident was last updated */
  updatedAt: string;

  /** Additional metadata */
  metadata?: Record<string, unknown>;
}

